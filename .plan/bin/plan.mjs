// ---------- git·경로 ----------
function git(args, cwd, input) {
  try {
    return execFileSync('git', args, { cwd, input, encoding: 'utf8', stdio: [input === undefined ? 'ignore' : 'pipe', 'pipe', 'ignore'] }).trimEnd();
  } catch {
    return null;
  }
}
function gitBuf(args, cwd) {
  try {
    return execFileSync('git', args, { cwd, stdio: ['ignore', 'pipe', 'ignore'] });
  } catch {
    return null;
  }
}
const sha256 = (buf) => crypto.createHash('sha256').update(buf).digest('hex');

export function paths(cwd) {
  const top = git(['rev-parse', '--show-toplevel'], cwd);
  if (!top) throw new Error('git 저장소 안에서 실행한다.');
  const common = git(['rev-parse', '--path-format=absolute', '--git-common-dir'], top);
  const gitDir = git(['rev-parse', '--path-format=absolute', '--git-dir'], top);
  const dir = path.join(common, 'plan');
  const linked = path.resolve(common) !== path.resolve(gitDir);
  return {
    top,
    common,
    dir,
    linked,
    mainTop: linked && path.basename(common) === '.git' ? path.dirname(common) : top,
    ledger: path.join(dir, 'ledger.jsonl'),
    inbox: path.join(dir, 'inbox'),
    lock: path.join(dir, '.lock'),
    capsule: path.join(top, CAPSULE_REL),
  };
}

// ---------- 원장 ----------
// 작업 파일이 없으면(CI 클론 등) 이력 ref에서 읽는다(읽기 전용).
export function readLedger(P) {
  let raw = null;
  let fromRef = false;
  if (fs.existsSync(P.ledger)) raw = fs.readFileSync(P.ledger);
  else {
    raw = gitBuf(['show', `${REF}:ledger.jsonl`], P.top);
    fromRef = raw !== null;
  }
  if (raw === null) return { events: [], raw: Buffer.alloc(0), fromRef, errors: ['공유 원장 없음. `plan init` 필요.'] };
  const events = [];
  const errors = [];
  raw
    .toString('utf8')
    .split('\n')
    .forEach((line, i) => {
      if (!line.trim()) return;
      try {
        events.push(JSON.parse(line));
      } catch {
        errors.push(`원장 ${i + 1}행: JSON 아님.`);
      }
    });
  return { events, raw, fromRef, errors };
}
// 스냅샷 파일(승인 계획·ADR)은 공유 디렉터리, 없으면 이력 ref에서 읽는다.
function readSnap(P, rel) {
  const f = path.join(P.dir, rel);
  return fs.existsSync(f) ? fs.readFileSync(f) : gitBuf(['show', `${REF}:${rel}`], P.top);
}

function withLock(P, fn) {
  fs.mkdirSync(P.dir, { recursive: true });
  for (let i = 0; i < 50; i++) {
    let fd;
    try {
      fd = fs.openSync(P.lock, 'wx');
    } catch (e) {
      if (e.code !== 'EEXIST') throw e;
      Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, 100);
      continue;
    }
    try {
      return fn();
    } finally {
      fs.closeSync(fd);
      fs.rmSync(P.lock, { force: true });
    }
  }
  throw new Error(`원장 잠금 획득 실패(${P.lock}). 다른 세션이 쓰는 중이 아니면 이 파일을 지운다.`);
}

// 공유 디렉터리 전체(ledger·revisions·adr)를 refs/plan/ledger 에 커밋으로 남긴다. 작업트리·인덱스는 건드리지 않는다.
function snapshot(P, message) {
  const mk = (entries) => git(['mktree'], P.top, entries.map((e) => `${e.mode} ${e.type} ${e.sha}\t${e.name}`).join('\n') + (entries.length ? '\n' : ''));
  const blob = (f) => git(['hash-object', '-w', f], P.top);
  const entries = [{ mode: '100644', type: 'blob', sha: blob(P.ledger), name: 'ledger.jsonl' }];
  for (const sub of ['adr', 'revisions']) {
    const d = path.join(P.dir, sub);
    if (!fs.existsSync(d)) continue;
    const files = fs.readdirSync(d).filter((f) => fs.statSync(path.join(d, f)).isFile()).sort();
    if (files.length) entries.push({ mode: '040000', type: 'tree', sha: mk(files.map((f) => ({ mode: '100644', type: 'blob', sha: blob(path.join(d, f)), name: f }))), name: sub });
  }
  const tree = mk(entries);
  const parent = git(['rev-parse', '--verify', '-q', REF], P.top);
  const env = { ...process.env };
  if (!git(['config', 'user.name'], P.top)) Object.assign(env, { GIT_AUTHOR_NAME: 'plan-harness', GIT_COMMITTER_NAME: 'plan-harness' });
  if (!git(['config', 'user.email'], P.top)) Object.assign(env, { GIT_AUTHOR_EMAIL: 'plan@localhost', GIT_COMMITTER_EMAIL: 'plan@localhost' });
  const commit = execFileSync('git', ['commit-tree', tree, ...(parent ? ['-p', parent] : []), '-m', message], { cwd: P.top, env, encoding: 'utf8' }).trim();
  execFileSync('git', ['update-ref', REF, commit, ...(parent ? [parent] : [])], { cwd: P.top, stdio: 'ignore' });
}

export function appendEvent(P, event, files = []) {
  return withLock(P, () => {
    const { events, errors, fromRef } = readLedger(P);
    if (errors.length) throw new Error(errors.join('\n'));
    if (fromRef) throw new Error('작업 원장이 없다(이력 ref만 있음). `plan restore`로 복구한 뒤 기록한다.');
    const full = { seq: (events.at(-1)?.seq ?? 0) + 1, ts: event.ts ?? new Date().toISOString(), ...event };
    const problems = validateEvents([...events, full]);
    if (problems.length) throw new Error(problems.join('\n'));
    for (const f of files) {
      fs.mkdirSync(path.dirname(path.join(P.dir, f.rel)), { recursive: true });
      fs.writeFileSync(path.join(P.dir, f.rel), f.buf);
    }
    fs.appendFileSync(P.ledger, JSON.stringify(full) + '\n');
    snapshot(P, `plan #${full.seq} ${full.type} ${full.id ?? full.rev ?? ''}`.trim());
    return full;
  });
}

// ---------- 접기(fold)와 전이 규칙 ----------
export function fold(events) {
  const s = { directives: new Map(), order: [], plans: [], plan: null, adrs: new Map(), triaged: new Set(), lastSeq: 0, planSeq: 0 };
  for (const e of events) {
    s.lastSeq = e.seq;
    if (e.type !== 'inbox.triage') s.planSeq = e.seq; // 입력 분류는 캡슐을 바꾸지 않는다.
    if (e.type === 'directive.add') {
      s.directives.set(e.id, { id: e.id, text: e.text, source: e.source, status: 'OPEN', ts: e.ts, seq: e.seq, amendments: [] });
      s.order.push(e.id);
    } else if (e.type === 'directive.amend') {
      s.directives.get(e.id)?.amendments.push({ text: e.text, source: e.source, seq: e.seq });
    } else if (e.type === 'directive.status') {
      const d = s.directives.get(e.id);
      if (!d) continue;
      Object.assign(d, {
        status: e.status,
        blocker: e.status === 'BLOCKED' ? e.blocker : undefined,
        unblock: e.status === 'BLOCKED' ? e.unblock : undefined,
        evidence: e.evidence ?? d.evidence,
        work: e.work ?? d.work,
        next: e.next ?? d.next,
      });
    } else if (e.type === 'order.set') {
      s.order = [...e.order, ...s.order.filter((id) => !e.order.includes(id))];
    } else if (e.type === 'plan.revise') {
      s.plans.push(e);
      s.plan = e;
    } else if (e.type === 'adr.status') {
      const prev = s.adrs.get(e.id) ?? {};
      s.adrs.set(e.id, {
        ...prev,
        id: e.id,
        file: e.file ?? prev.file,
        status: e.status,
        statusSeq: e.seq,
        supersededBy: e.superseded_by ?? prev.supersededBy,
        acceptedSeq: e.status === 'accepted' ? e.seq : prev.acceptedSeq,
      });
    } else if (e.type === 'adr.impact') {
      const a = s.adrs.get(e.id);
      if (a) Object.assign(a, { impact: e.impact, impactReason: e.reason, impactBy: e.by, impactSeq: e.seq });
    } else if (e.type === 'inbox.triage') {
      for (const r of e.refs ?? [e.ref]) s.triaged.add(r);
    }
  }
  return s;
}

// 원장 전체를 처음부터 다시 검증한다. CLI를 우회해 손으로 추가한 줄도 여기서 걸린다.
export function validateEvents(events) {
  const errs = [];
  const seen = new Set();
  const dirs = new Map();
  const adrs = new Map();
  let lastSeq = 0;
  let lastRev = 0;
  for (const e of events) {
    const at = `#${e.seq ?? '?'}(${e.type ?? '?'})`;
    if (!Number.isInteger(e.seq) || e.seq !== lastSeq + 1) errs.push(`${at}: seq는 1씩 증가해야 한다(직전 ${lastSeq}).`);
    lastSeq = e.seq;
    if (!e.ts || Number.isNaN(Date.parse(e.ts))) errs.push(`${at}: ts 없음.`);
    const needUser = (why) => {
      if (e.by !== 'user' || !String(e.quote ?? '').trim()) errs.push(`${at}: ${why}는 사용자 원문(by=user, quote)이 필요하다.`);
    };
    switch (e.type) {
      case 'directive.add':
        if (!/^DIR-\d{3,}$/.test(e.id ?? '')) errs.push(`${at}: 지시 ID 형식은 DIR-001.`);
        if (seen.has(e.id)) errs.push(`${at}: ${e.id} 중복.`);
        if (!String(e.text ?? '').trim() || !String(e.source ?? '').trim()) errs.push(`${at}: 지시는 원문(text)과 출처(source)가 필요하다.`);
        seen.add(e.id);
        dirs.set(e.id, 'OPEN');
        break;
      case 'directive.amend':
        if (!dirs.has(e.id)) errs.push(`${at}: 없는 지시 ${e.id}.`);
        if (!String(e.text ?? '').trim() || !String(e.source ?? '').trim()) errs.push(`${at}: 변경 원문과 출처가 필요하다.`);
        break;
      case 'directive.status': {
        const cur = dirs.get(e.id);
        if (!cur) {
          errs.push(`${at}: 없는 지시 ${e.id}.`);
          break;
        }
        if (!STATUSES.has(e.status)) errs.push(`${at}: 알 수 없는 상태 ${e.status}.`);
        if (TERMINAL.has(cur)) errs.push(`${at}: ${e.id}는 이미 ${cur}(종결)이다. 다시 열려면 새 지시로 추가한다.`);
        if (USER_ONLY.has(e.status)) needUser(`${e.status} 전이`);
        if (e.status === 'DONE' && cur !== 'VERIFY') errs.push(`${at}: DONE은 VERIFY(증거 제출) 뒤에만 가능하다.`);
        if (e.status === 'VERIFY' && !String(e.evidence ?? '').trim()) errs.push(`${at}: VERIFY는 증거(evidence)가 필요하다.`);
        if (e.status === 'BLOCKED' && (!String(e.blocker ?? '').trim() || !String(e.unblock ?? '').trim()))
          errs.push(`${at}: BLOCKED는 막힘 사유(blocker)와 해제 조건(unblock)이 필요하다.`);
        if (e.status === 'SUPERSEDED' && !String(e.superseded_by ?? '').trim()) errs.push(`${at}: SUPERSEDED는 superseded_by가 필요하다.`);
        dirs.set(e.id, e.status);
        break;
      }
      case 'order.set':
        needUser('순서 변경');
        for (const id of e.order ?? []) if (!dirs.has(id)) errs.push(`${at}: 없는 지시 ${id}.`);
        break;
      case 'plan.revise': {
        const before = lastRev;
        needUser('계획 개정 승인');
        if (before === 0 ? !(Number.isInteger(e.rev) && e.rev >= 1) : e.rev !== before + 1)
          errs.push(`${at}: 계획 revision은 ${before === 0 ? '1 이상(기존 계획 이관 시 현재 번호)' : before + 1}이어야 한다.`);
        lastRev = e.rev ?? lastRev;
        if (!REVISE_REASONS.has(e.reason)) errs.push(`${at}: 개정 사유는 ${[...REVISE_REASONS].join('|')} 중 하나.`);
        if (e.reason === 'BASELINE' && before !== 0) errs.push(`${at}: BASELINE은 첫 revision(기존 계획 이관)에만 쓴다.`);
        if (e.reason !== 'BASELINE' && (!Array.isArray(e.triggers) || e.triggers.length === 0)) errs.push(`${at}: 개정 트리거(지시·ADR ID)가 필요하다.`);
        for (const t of e.triggers ?? []) if (!dirs.has(t) && !adrs.has(t)) errs.push(`${at}: 트리거 ${t}가 원장에 없다.`);
        if (!e.snapshot || !/^[0-9a-f]{64}$/.test(e.sha256 ?? '')) errs.push(`${at}: 계획 스냅샷과 sha256이 필요하다.`);
        break;
      }
      case 'adr.status':
        if (!/^ADR-\d{3,}$/.test(e.id ?? '')) errs.push(`${at}: ADR ID 형식은 ADR-001(또는 ADR-0001).`);
        if (!ADR_STATUSES.has(e.status)) errs.push(`${at}: ADR 상태는 ${[...ADR_STATUSES].join('|')}.`);
        if (!adrs.has(e.id) && !e.file) errs.push(`${at}: 첫 ADR 이벤트는 file이 필요하다.`);
        if (e.status === 'superseded' && adrs.get(e.superseded_by) !== 'accepted') errs.push(`${at}: 대체하는 ${e.superseded_by}가 먼저 accepted여야 한다.`);
        adrs.set(e.id, e.status);
        break;
      case 'adr.impact':
        if (!adrs.has(e.id)) errs.push(`${at}: 없는 ADR ${e.id}.`);
        if (e.impact !== 'none' || !String(e.reason ?? '').trim()) errs.push(`${at}: adr.impact는 impact=none과 사유가 필요하다(영향이 있으면 계획 개정으로 처리).`);
        break;
      case 'inbox.triage':
        if (!(e.ref || (Array.isArray(e.refs) && e.refs.length)) || !e.as) errs.push(`${at}: triage는 ref(또는 refs)와 as가 필요하다.`);
        break;
      default:
        errs.push(`${at}: 알 수 없는 이벤트.`);
    }
  }
  return errs;
}

// ---------- 캡슐 렌더(결정적) ----------
const oneLine = (t) => String(t ?? '').replace(/\s+/g, ' ').trim();
const cut = (t, n) => {
  const cps = Array.from(oneLine(t)); // 코드포인트 단위로 자른다(한글 바이트 절단 방지).
  return cps.length <= n ? cps.join('') : cps.slice(0, n).join('') + '…';
};

export function renderCapsule(state, { excerpt = 70 } = {}) {
  const L = [BEGIN, `## 계획 캡슐 · 공유 원장 #${state.planSeq} (모든 브랜치·작업트리 공통)`];
  if (state.plan) {
    const p = state.plan;
    L.push(`계획: REV-${p.rev} ${p.file} sha:${p.sha256.slice(0, 8)} · 사유 ${p.reason} · 트리거 ${p.triggers.join(',') || '-'}`);
  } else L.push('계획: 승인된 revision 없음 → 사용자 승인 후 `plan revise` 필요');
  const live = state.order.map((id) => state.directives.get(id)).filter((d) => d && !TERMINAL.has(d.status));
  const work = live.filter((d) => d.status !== 'VERIFY');
  const verify = live.filter((d) => d.status === 'VERIFY');
  L.push('사용자 지시(순서·범위·완료는 사용자만 바꾼다):');
  if (work.length === 0) L.push('- (열린 지시 없음)');
  work.forEach((d, i) => {
    let line = `${i + 1}. ${d.id} ${d.status}`;
    if (excerpt > 0) line += ` 「${cut(d.text, excerpt)}」`;
    if (d.amendments.length) line += ` +변경${d.amendments.length}`;
    if (d.status === 'BLOCKED') line += ` 막힘:${cut(d.blocker, 40)} 해제:${cut(d.unblock, 40)}`;
    else if (d.next && excerpt > 0) line += ` 다음:${cut(d.next, 40)}`;
    L.push(line);
  });
  if (verify.length) L.push(`완료 확인 대기(VERIFY, 사용자 선언 필요): ${verify.map((d) => d.id).join(', ')}`);
  const pending = pendingAdrs(state);
  if (pending.length) L.push(`계획 미반영 결정: ${pending.map((a) => a.id).join(', ')} → \`plan revise\` 또는 \`plan adr impact --none\` 필요`);
  const proposed = [...state.adrs.values()].filter((a) => a.status === 'proposed');
  if (proposed.length) L.push(`결정 대기 ADR(제안 상태, 사용자 수락·기각 필요): ${proposed.map((a) => a.id).join(', ')}`);
  L.push('규칙: ①순서·범위·완료는 사용자만 ②선택지 1번은 「지시대로 즉시 진행」, 막힘 증거 없는 지연안에 (권장) 금지 ③원장·캡슐·승인 계획은 `plan` CLI로만');
  L.push('④STATE·메모리·인계서에 원장에 없는 순서를 쓰지 않음 ⑤작업 폴더와 지시 대상이 다르면 먼저 알림 ⑥세션 끝 `plan check --close`');
  L.push(END);
  return L.join('\n') + '\n';
}

export function renderCapsuleWithinBudget(state) {
  for (const excerpt of [70, 40, 20, 0]) {
    const text = renderCapsule(state, { excerpt });
    if (Buffer.byteLength(text, 'utf8') <= CAPSULE_BUDGET) return text;
  }
  throw new Error(`캡슐이 ${CAPSULE_BUDGET}바이트를 넘는다(열린 지시 과다). 지시를 자르지 않는다. 사용자와 병합·종결(SUPERSEDED/DROPPED)을 결정해야 한다.`);
}

// accepted 이후의 계획 revision 트리거에도, 영향 없음 선언에도 없는 ADR = 계획이 결정 변경을 따라가지 못한 상태.
export function pendingAdrs(state) {
  return [...state.adrs.values()].filter((a) => {
    if (a.status !== 'accepted') return false;
    const acc = a.acceptedSeq ?? 0;
    const revised = state.plans.some((p) => p.seq > acc && (p.triggers ?? []).includes(a.id));
    const noImpact = a.impact === 'none' && (a.impactSeq ?? 0) > acc;
    return !revised && !noImpact;
  });
}

// ---------- ADR 파일 상태 ----------
const ADR_WORDS = { 확정: 'accepted', accepted: 'accepted', 승인: 'accepted', 채택: 'accepted', 수락: 'accepted', 수락됨: 'accepted', proposed: 'proposed', 제안: 'proposed', superseded: 'superseded', 대체: 'superseded', 대체됨: 'superseded', deprecated: 'deprecated', 폐기: 'deprecated', rejected: 'rejected', 기각: 'rejected' };
const STATUS_LINE = /^(\s*(?:[-*]\s*)?(?:\*\*)?(?:status|상태)(?:\*\*)?\s*[:：.]\s*(?:\*\*)?\s*)([A-Za-z가-힣]+)(.*)$/im;
// 인식 가능한 상태면 표준 값, 상태 줄이 없거나 자유 문장("재검토 필요", "단계적 교체 결정")이면 null.
const STATUS_HEADING = /^#{2,4}\s*(?:status|상태)\.?\s*\n+\s*(?:[-*]\s*)?(?:\*\*)?([A-Za-z가-힣]+)/im; // "## 상태." 다음 줄에 값을 쓰는 형식
export function adrFileStatus(text) {
  const m = String(text).match(STATUS_LINE) ?? String(text).match(STATUS_HEADING);
  if (!m) return null;
  const w = (m[2] ?? m[1]).toLowerCase();
  return ADR_WORDS[w] ?? ADR_WORDS[w.replace(/됨$/, '')] ?? null;
}
export function adrStatusRaw(text) {
  return (String(text).match(STATUS_LINE)?.[0] ?? '').trim().slice(0, 60);
}
function setAdrFileStatus(file, status, note) {
  const text = fs.readFileSync(file, 'utf8');
  if (!note && adrFileStatus(text) === status) return text; // 이미 같은 상태(한국어 표기 포함)면 파일을 건드리지 않는다.
  const next = adrFileStatus(text) !== null && STATUS_LINE.test(text)
    ? text.replace(STATUS_LINE, (_, pre) => `${pre}${status}${note ? ` ${note}` : ''}`)
    : text.replace(/^(# .*\n)/, `$1\nStatus: ${status}${note ? ` ${note}` : ''}\n`);
  fs.writeFileSync(file, next);
  return next;
}

// ---------- AGENTS.md 규칙 블록 ----------
export function withRules(agents) {
  if (agents.includes(RULES_BEGIN)) return agents;
  if (!agents.trim()) return RULES_BLOCK + '\n';
  const lines = agents.split('\n');
  const at = /^#\s/.test(lines[0]) ? 1 : 0; // 첫 제목 바로 아래. 파일 끝은 Codex 32KiB 상한에서 먼저 잘리고, 중간은 주의가 약하다.
  return [...lines.slice(0, at), ...(at ? [''] : []), RULES_BLOCK, '', ...lines.slice(at)].join('\n').replace(/\n{3,}/g, '\n\n');
}

// 본문이 ID를 언급하는지. ADR은 "ADR-0014", "ADR 0014", "0014-파일명"처럼 번호만 쓴 표기도 인정한다.
export function mentions(body, id) {
  if (body.includes(id)) return true;
  const m = id.match(/^ADR-(\d{3,4})$/);
  if (!m) return false;
  if (new RegExp(`(ADR[\\s_-]?${m[1]}\\b|(^|[^0-9])${m[1]}-[a-z])`, 'i').test(body)) return true;
  // 범위 표기 "ADR-0009~0013", "ADR 0009–0013"
  const n = Number(m[1]);
  for (const r of body.matchAll(/ADR[\s_-]?(\d{3,4})\s*[~–—-]\s*(?:ADR[\s_-]?)?(\d{3,4})/gi)) if (n >= Number(r[1]) && n <= Number(r[2])) return true;
  return false;
}

// ---------- 검사 ----------
export function check(P, { close = false } = {}) {
  const errors = [];
  const warns = [];
  const { events, raw, errors: parseErrs, fromRef } = readLedger(P);
  errors.push(...parseErrs);
  if (parseErrs.length) return { errors, warns };
  errors.push(...validateEvents(events));
  const state = fold(events);

  // 1) 추가 전용: 작업 원장 = 이력 ref 최신본이어야 한다. 이력 자체도 직전 스냅샷의 연장이어야 한다.
  const refLedger = gitBuf(['show', `${REF}:ledger.jsonl`], P.top);
  if (refLedger && !fromRef && !raw.equals(refLedger)) {
    if (raw.length > refLedger.length && raw.subarray(0, refLedger.length).equals(refLedger)) errors.push('CLI 밖에서 원장에 줄이 추가됐다. 추가분을 지우고(`plan restore`) plan 명령으로 다시 기록한다.');
    else errors.push('원장이 기록 이력(refs/plan/ledger) 대비 추가 전용이 아니다(삭제·수정). `plan restore`로 이력본을 복구한다.');
  }
  const parentLedger = gitBuf(['show', `${REF}~1:ledger.jsonl`], P.top);
  if (refLedger && parentLedger && !refLedger.subarray(0, parentLedger.length).equals(parentLedger)) errors.push('이력 ref가 재작성됐다(직전 스냅샷의 연장이 아님). `git reflog refs/plan/ledger`로 확인한다.');

  // 2) 승인 계획 스냅샷 불변, 본문이 트리거를 언급하는지, 작업 사본이 다른지.
  for (const p of state.plans) {
    const buf = readSnap(P, p.snapshot);
    if (!buf) {
      errors.push(`REV-${p.rev} 스냅샷 ${p.snapshot} 없음.`);
      continue;
    }
    if (sha256(buf) !== p.sha256) errors.push(`REV-${p.rev} 승인 계획 스냅샷이 승인 후 바뀌었다. 새 revision으로 개정한다.`);
    const body = buf.toString('utf8');
    for (const t of p.triggers ?? []) if (!mentions(body, t)) errors.push(`REV-${p.rev} 계획 본문이 트리거 ${t}를 언급하지 않는다(결정이 계획에 반영되지 않음).`);
    const wc = path.join(P.top, p.file);
    // 최신 승인본과 다른 계획 파일 = 승인되지 않은 계획 변경. 세션 중에는 경고, 세션 종료 때는 막는다(사용자 승인 → plan revise, 또는 되돌림).
    const latestForFile = [...state.plans].reverse().find((q) => q.file === p.file);
    if (p === latestForFile && fs.existsSync(wc) && sha256(fs.readFileSync(wc)) !== p.sha256)
      (close ? errors : warns).push(`${p.file}이 승인본 REV-${p.rev}와 다르다(승인되지 않은 계획 변경). 사용자 승인을 받아 \`plan revise --file ${p.file}\`로 새 revision을 등록하거나 되돌린다.`);
  }

  // 3) ADR: 현재 브랜치에 파일이 있으면 상태 줄이 원장과 같아야 하고, 없으면 다른 브랜치에만 있는 결정이다.
  for (const a of state.adrs.values()) {
    const f = path.join(P.top, a.file ?? '');
    if (!a.file || !fs.existsSync(f)) {
      warns.push(`${a.id}(${a.status})가 현재 브랜치에 없다(${a.file}). 다른 브랜치에서 결정됐다 → 정본 브랜치로 병합한다.`);
      continue;
    }
    const text = fs.readFileSync(f, 'utf8');
    const fileStatus = adrFileStatus(text);
    if (fileStatus === null) warns.push(`${a.id} 파일 상태 줄이 없거나 인식할 수 없다(${adrStatusRaw(text) || '없음'}). 원장 상태 ${a.status} 기준. 사용자 확인 후 \`plan adr accept|propose\`로 표기를 맞춘다.`);
    else if (fileStatus !== a.status) errors.push(`${a.id} 파일 상태(${fileStatus ?? '없음'})가 원장(${a.status})과 다르다. \`plan adr\` 로만 바꾼다.`);
  }

  // 4) ADR → 계획 반영.
  for (const a of pendingAdrs(state)) (close ? errors : warns).push(`${a.id}가 현재 계획(REV-${state.plan?.rev ?? 0}) 이후 accepted 됐지만 계획에 반영되지 않았다.`);

  // 5) 캡슐 예산·완전성·신선도(작업트리 사본은 생성물이라 낡으면 경고).
  let capsule = null;
  try {
    capsule = renderCapsuleWithinBudget(state);
  } catch (e) {
    errors.push(e.message);
  }
  if (capsule) {
    for (const d of state.directives.values()) if (!TERMINAL.has(d.status) && !capsule.includes(d.id)) errors.push(`캡슐에 열린 지시 ${d.id}가 없다.`);
    const cur = fs.existsSync(P.capsule) ? fs.readFileSync(P.capsule, 'utf8') : null;
    if (cur !== capsule) warns.push(`${CAPSULE_REL}가 원장보다 낡았다(다른 세션이 기록함). \`plan render\` 로 갱신한다.`);
  }

  // 6) 진입 문서: AGENTS.md 규칙 블록, 크기, Claude가 AGENTS.md·캡슐을 불러오는지.
  const agentsFile = path.join(P.top, 'AGENTS.md');
  if (!fs.existsSync(agentsFile)) errors.push('AGENTS.md 없음(모든 도구가 읽는 공통 진입점).');
  else {
    const agents = fs.readFileSync(agentsFile, 'utf8');
    if (!agents.includes(RULES_BEGIN)) errors.push('AGENTS.md에 PLAN-RULES 블록이 없다. `plan init`으로 넣는다.');
    const size = Buffer.byteLength(agents);
    if (size > 32 * 1024) errors.push(`AGENTS.md ${size}B > 32KiB(Codex 기본 project_doc_max_bytes). 뒷부분이 잘린다.`);
    else if (size > 12 * 1024) warns.push(`AGENTS.md ${size}B. 진입 문서는 짧게(지도 역할) 유지한다.`);
  }
  const claudeFile = path.join(P.top, 'CLAUDE.md');
  if (fs.existsSync(claudeFile)) {
    const c = fs.readFileSync(claudeFile, 'utf8');
    if (!/^@AGENTS\.md\s*$/m.test(c)) errors.push('CLAUDE.md가 @AGENTS.md를 불러오지 않는다(링크만으로는 Claude가 AGENTS.md를 읽지 않는다).');
    if (!/^@\.plan\/CAPSULE\.md\s*$/m.test(c)) warns.push('CLAUDE.md가 @.plan/CAPSULE.md를 불러오지 않는다(압축 뒤 캡슐 재적재가 훅에만 의존).');
  }

  // 7) 세션 종료 시 미분류 사용자 입력 0.
  const inbox = listInbox(P);
  const untriaged = inbox.filter((x) => !state.triaged.has(x.id));
  if (untriaged.length) (close ? errors : warns).push(`미분류 사용자 입력 ${untriaged.length}건. \`plan triage --list\` 로 분류한다.`);

  // 8) "사용자 승인" 인용이 실제 입력에 있었는지(지어낸 승인 탐지). inbox는 로컬 전용이라 CI에서는 건너뛴다.
  const norm = (t) => oneLine(t).replace(/[「」"'`]/g, '');
  const said = inbox.map((x) => norm(x.prompt));
  const quoted = events.filter((e) => e.by === 'user' && e.quote);
  if (quoted.length && !said.length) warns.push('입력 포착(inbox)이 없어 사용자 인용을 대조할 수 없다. 도구별 capture 훅을 설치한다.');
  else for (const e of quoted) if (!said.some((s) => s.includes(norm(e.quote)))) warns.push(`#${e.seq} ${e.type} 사용자 인용 「${cut(e.quote, 30)}」이 포착된 입력에 없다(지어낸 승인 의심).`);
  return { errors, warns, state };
}

// ---------- 입력 포착(inbox, git 밖·공유) ----------
export function listInbox(P) {
  if (!fs.existsSync(P.inbox)) return [];
  return fs
    .readdirSync(P.inbox)
    .filter((f) => f.endsWith('.jsonl'))
    .sort()
    .flatMap((f) =>
      fs
        .readFileSync(path.join(P.inbox, f), 'utf8')
        .split('\n')
        .filter(Boolean)
        .map((l) => {
          try {
            return JSON.parse(l);
          } catch {
            return null;
          }
        })
        .filter(Boolean),
    );
}
export function capture(P, { tool, payload }) {
  let obj = {};
  try {
    obj = JSON.parse(payload || '{}');
  } catch {
    obj = { prompt: payload };
  }
  const prompt = obj.prompt ?? obj.user_prompt ?? obj.message ?? obj.input ?? '';
  if (!String(prompt).trim()) return null;
  const ts = new Date().toISOString();
  const rec = { id: sha256(ts + prompt).slice(0, 12), ts, tool, session: obj.session_id ?? obj.sessionId ?? null, cwd: obj.cwd ?? P.top, prompt };
  fs.mkdirSync(P.inbox, { recursive: true });
  fs.appendFileSync(path.join(P.inbox, `${ts.slice(0, 7)}.jsonl`), JSON.stringify(rec) + '\n');
  return rec;
}
// 사용자 인용으로 쓰인 입력은 그 이벤트의 근거로 자동 분류한다.
export function consumeQuote(P, ev) {
  if (!ev?.quote) return;
  const q = oneLine(ev.quote);
  const state = fold(readLedger(P).events);
  const refs = listInbox(P)
    .filter((x) => !state.triaged.has(x.id) && oneLine(x.prompt).includes(q))
    .map((x) => x.id);
  if (refs.length) appendEvent(P, { type: 'inbox.triage', refs, as: `quote:#${ev.seq}` });
}

// ---------- 렌더·주입 ----------
export function render(P) {
  const capsule = renderCapsuleWithinBudget(fold(readLedger(P).events));
  fs.mkdirSync(path.dirname(P.capsule), { recursive: true });
  fs.writeFileSync(P.capsule, capsule);
  return capsule;
}

// 훅용. 공유 원장에서 캡슐을 만들고 이 작업트리의 캡슐 사본도 갱신한다. 실패해도 조용히 사라지지 않는다.
export function inject(cwd, { event = 'startup', format = 'text' } = {}) {
  let body;
  try {
    const P = paths(cwd);
    const { events, errors } = readLedger(P);
    if (errors.length) throw new Error(errors.join(' '));
    const state = fold(events);
    const capsule = renderCapsuleWithinBudget(state);
    try {
      if (!fs.existsSync(P.capsule) || fs.readFileSync(P.capsule, 'utf8') !== capsule) {
        fs.mkdirSync(path.dirname(P.capsule), { recursive: true });
        fs.writeFileSync(P.capsule, capsule);
      }
    } catch {}
    const notes = [];
    if (event === 'compact') notes.push('[plan] 컨텍스트가 압축됐다. 요약보다 아래 캡슐이 우선한다.');
    const untriaged = listInbox(P).filter((x) => !state.triaged.has(x.id)).length;
    if (untriaged) notes.push(`[plan] 미분류 사용자 입력 ${untriaged}건 → 세션 끝에 \`plan triage --list\`.`);
    body = (notes.length ? notes.join('\n') + '\n' : '') + capsule;
  } catch (e) {
    body = `[plan] 캡슐 주입 실패: ${e.message}\n\`node .plan/bin/plan.mjs inject\` 를 직접 실행하고, 실패를 사용자에게 먼저 알린다.`;
  }
  if (format === 'claude' || format === 'codex') {
    const hookEventName = event === 'prompt' ? 'UserPromptSubmit' : 'SessionStart';
    return JSON.stringify({ hookSpecificOutput: { hookEventName, additionalContext: body } });
  }
  return body;
}

// 매 입력마다 붙이는 한 줄 알림(1순위 지시만).
export function remind(cwd) {
  try {
    const state = fold(readLedger(paths(cwd)).events);
    const top = state.order.map((id) => state.directives.get(id)).find((d) => d && !TERMINAL.has(d.status) && d.status !== 'VERIFY');
    return top ? `[plan] 1순위 사용자 지시 ${top.id} ${top.status} 「${cut(top.text, 50)}」. 새 지시·변경이면 세션 끝에 triage.` : '';
  } catch {
    return '';
  }
}

// ---------- 보호 경로(PreToolUse) ----------
// 심볼릭 경로(macOS /var → /private/var 등)를 git이 돌려주는 실제 경로에 맞춘다. 아직 없는 파일은 가장 가까운 기존 상위 폴더 기준.
function real(p) {
  let cur = path.resolve(p);
  const rest = [];
  while (!fs.existsSync(cur)) {
    const parent = path.dirname(cur);
    if (parent === cur) break;
    rest.unshift(path.basename(cur));
    cur = parent;
  }
  try {
    cur = fs.realpathSync(cur);
  } catch {}
  return path.join(cur, ...rest);
}
export function guard(cwd, payload) {
  let obj = {};
  try {
    obj = JSON.parse(payload || '{}');
  } catch {
    return null;
  }
  const input = obj.tool_input ?? obj.input ?? {};
  const target = input.file_path ?? input.path ?? input.filePath ?? '';
  if (!target) return null;
  const P = paths(cwd);
  const abs = real(path.resolve(cwd, target));
  if (abs.startsWith(real(P.dir) + path.sep)) return '공유 원장(.git/plan)은 직접 수정하지 않는다. `plan` CLI를 쓴다.';
  const rel = path.relative(real(P.top), abs).split(path.sep).join('/');
  const state = fold(readLedger(P).events);
  // 승인된 계획 파일은 편집을 막지 않는다(ADR·지시 반영을 위해 고쳐야 한다). 대신 승인 전 변경은 종료 게이트가 막는다.
  if (rel === CAPSULE_REL) return `${rel}은 원장에서 생성되는 보기다. 직접 수정하지 말고 \`plan\` CLI를 쓴다.`;
  const planDirs = new Set(state.plans.map((p) => path.posix.dirname(p.file)).filter((d) => d !== '.'));
  if (!fs.existsSync(abs) && COMPETING_PLAN.test(rel) && !/^docs\/plan\/REV-\d+/.test(rel) && !state.plans.some((p) => p.file === rel) && !planDirs.has(path.posix.dirname(rel)))
    return `${rel}: 계획 정본이 있는 프로젝트에서 새 계획·체크리스트 파일을 만들지 않는다. docs/plan/REV-NNN.md 초안을 쓰고 사용자 승인 후 \`plan revise\`로 등록한다.`;
  return null;
}

// ---------- 지표 ----------
export function metrics(P) {
  const { events } = readLedger(P);
  const state = fold(events);
  const hours = (a, b) => (Date.parse(b) - Date.parse(a)) / 36e5;
  const median = (xs) => {
    if (!xs.length) return null;
    const s = [...xs].sort((a, b) => a - b);
    return +(s.length % 2 ? s[(s.length - 1) / 2] : (s[s.length / 2 - 1] + s[s.length / 2]) / 2).toFixed(1);
  };
  const firstActive = [];
  for (const d of state.directives.values()) {
    const ev = events.find((e) => e.type === 'directive.status' && e.id === d.id && ['ACTIVE', 'VERIFY'].includes(e.status));
    if (ev) firstActive.push(hours(d.ts, ev.ts));
  }
  const adrLag = [];
  for (const a of state.adrs.values()) {
    const acc = events.find((e) => e.seq === a.acceptedSeq);
    const rev = state.plans.find((p) => p.seq > (a.acceptedSeq ?? 0) && (p.triggers ?? []).includes(a.id));
    if (acc && rev) adrLag.push(hours(acc.ts, rev.ts));
  }
  const byStatus = {};
  for (const d of state.directives.values()) byStatus[d.status] = (byStatus[d.status] ?? 0) + 1;
  const weekAgo = Date.now() - 7 * 864e5;
  let capsuleBytes = null;
  try {
    capsuleBytes = Buffer.byteLength(renderCapsuleWithinBudget(state), 'utf8');
  } catch {}
  return {
    directives: byStatus,
    directive_to_first_action_hours_median: median(firstActive),
    plan_revisions_total: state.plans.length,
    plan_revisions_last_7d: state.plans.filter((p) => Date.parse(p.ts) > weekAgo).length,
    adr_accept_to_plan_hours_median: median(adrLag),
    adr_pending_plan: pendingAdrs(state).map((a) => a.id),
    adr_no_impact_by_agent: [...state.adrs.values()].filter((a) => a.impact === 'none' && a.impactBy !== 'user').map((a) => a.id),
    inbox_untriaged: listInbox(P).filter((x) => !state.triaged.has(x.id)).length,
    capsule_bytes: capsuleBytes,
  };
}

// ---------- CLI ----------
function parseArgs(argv) {
  const pos = [];
  const flags = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i];
    if (a.startsWith('--')) {
      const k = a.slice(2);
      const v = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : true;
      flags[k] = v;
    } else pos.push(a);
  }
  return { pos, flags };
}
const readStdin = () => {
  try {
    return fs.readFileSync(0, 'utf8');
  } catch {
    return '';
  }
};
const nextId = (prefix, ids) => `${prefix}-${String(Math.max(0, ...[...ids].map((id) => +id.split('-')[1] || 0)) + 1).padStart(3, '0')}`;

export function main(argv, cwd = process.cwd()) {
  const { pos, flags } = parseArgs(argv);
  const [cmd, sub, arg] = pos;
  const out = (s) => {
    process.stdout.write(s.endsWith('\n') ? s : s + '\n');
    return 0;
  };
  const by = flags.quote ? 'user' : 'agent';
  if (cmd === 'inject') {
    // 훅 stdin(JSON)에서 시작 원인을 읽는다. Claude·Codex는 source, Grok은 camelCase 키를 쓴다.
    let event = flags.event ?? 'startup';
    if (flags['from-stdin']) {
      try {
        const o = JSON.parse(readStdin() || '{}');
        const name = String(o.hook_event_name ?? o.hookEventName ?? '');
        event = /compact/i.test(name) ? 'compact' : (o.source ?? o.trigger ?? event);
      } catch {}
    }
    return out(inject(cwd, { event, format: flags.format ?? 'text' }));
  }
  const P = paths(cwd);
  switch (cmd) {
    case 'init': {
      fs.mkdirSync(P.inbox, { recursive: true });
      if (!fs.existsSync(P.ledger)) {
        const fromRef = gitBuf(['show', `${REF}:ledger.jsonl`], P.top);
        fs.writeFileSync(P.ledger, fromRef ?? '');
        if (!fromRef) snapshot(P, 'plan init');
      }
      fs.mkdirSync(path.join(P.top, '.plan'), { recursive: true });
      const cfg = path.join(P.top, '.plan', 'config.json');
      if (!fs.existsSync(cfg)) fs.writeFileSync(cfg, JSON.stringify({ version: 3, ledger: '<git-common-dir>/plan/ledger.jsonl', history_ref: REF }, null, 2) + '\n');
      const gi = path.join(P.top, '.gitignore');
      const cur = fs.existsSync(gi) ? fs.readFileSync(gi, 'utf8') : '';
      if (!cur.includes(CAPSULE_REL)) fs.appendFileSync(gi, `${cur && !cur.endsWith('\n') ? '\n' : ''}${CAPSULE_REL}\n`);
      const agentsFile = path.join(P.top, 'AGENTS.md');
      const agents = fs.existsSync(agentsFile) ? fs.readFileSync(agentsFile, 'utf8') : '';
      const next = withRules(agents);
      if (next !== agents) fs.writeFileSync(agentsFile, next);
      render(P);
      return out(`초기화 완료: 공유 원장 ${P.ledger}, 이력 ${REF}, AGENTS.md 규칙 블록, ${CAPSULE_REL}.`);
    }
    case 'restore': {
      const refLedger = gitBuf(['show', `${REF}:ledger.jsonl`], P.top);
      if (!refLedger) throw new Error('이력 ref가 없다.');
      fs.mkdirSync(P.dir, { recursive: true });
      fs.writeFileSync(P.ledger, refLedger);
      render(P);
      return out(`원장을 ${REF} 최신 스냅샷으로 복구했다.`);
    }
    case 'directive': {
      const state = fold(readLedger(P).events);
      if (sub === 'add') {
        let text = flags.text;
        let source = flags.source;
        if (flags['from-inbox']) {
          const rec = listInbox(P).find((x) => x.id === flags['from-inbox']);
          if (!rec) throw new Error(`inbox ${flags['from-inbox']} 없음.`);
          text = rec.prompt;
          source = `inbox:${rec.id}:${rec.tool}:${rec.ts}`;
        }
        const id = nextId('DIR', state.directives.keys());
        appendEvent(P, { type: 'directive.add', id, text, source, by: 'user' });
        if (flags['from-inbox']) appendEvent(P, { type: 'inbox.triage', ref: flags['from-inbox'], as: id });
        render(P);
        return out(id);
      }
      if (sub === 'amend') {
        appendEvent(P, { type: 'directive.amend', id: arg, text: flags.text, source: flags.source, by: 'user' });
        render(P);
        return out(`${arg} 변경 기록.`);
      }
      if (sub === 'set') {
        const ev = { type: 'directive.status', id: arg, status: flags.status, by, quote: flags.quote };
        for (const k of ['evidence', 'blocker', 'unblock', 'work', 'next', 'superseded_by']) if (flags[k]) ev[k] = flags[k];
        consumeQuote(P, appendEvent(P, ev));
        render(P);
        return out(`${arg} → ${flags.status}.`);
      }
      break;
    }
    case 'order':
      consumeQuote(P, appendEvent(P, { type: 'order.set', order: String(flags.ids).split(','), by, quote: flags.quote }));
      render(P);
      return out('순서 기록.');
    case 'revise': {
      const state = fold(readLedger(P).events);
      const file = String(flags.file);
      const buf = fs.readFileSync(path.join(P.top, file));
      const rev = state.plan ? state.plan.rev + 1 : Number(flags.rev ?? 1);
      const snap = `revisions/REV-${String(rev).padStart(3, '0')}.md`;
      const ev = appendEvent(
        P,
        {
          type: 'plan.revise',
          rev,
          file,
          snapshot: snap,
          sha256: sha256(buf),
          reason: flags.baseline ? 'BASELINE' : flags.reason,
          triggers: String(flags.triggers ?? '').split(',').filter(Boolean),
          by,
          quote: flags.quote,
        },
        [{ rel: snap, buf }],
      );
      consumeQuote(P, ev);
      render(P);
      return out(`REV-${rev} 등록(스냅샷 ${snap}).`);
    }
    case 'adr': {
      const state = fold(readLedger(P).events);
      const snapOf = (id, text) => [{ rel: `adr/${id}.md`, buf: Buffer.from(text) }];
      if (sub === 'accept' || sub === 'propose') {
        const status = sub === 'accept' ? 'accepted' : 'proposed';
        const file = flags.file ?? state.adrs.get(arg)?.file;
        const f = path.join(P.top, file);
        const before = fs.readFileSync(f, 'utf8');
        const after = setAdrFileStatus(f, status);
        try {
          appendEvent(P, { type: 'adr.status', id: arg, status, file, by }, snapOf(arg, after));
        } catch (e) {
          if (after !== before) fs.writeFileSync(f, before); // 원장 기록이 거부되면 파일도 되돌린다.
          throw e;
        }
        render(P);
        return out(`${arg} ${status}.`);
      }
      if (sub === 'supersede') {
        const old = state.adrs.get(arg);
        if (!old) throw new Error(`원장에 없는 ADR ${arg}.`);
        const f = path.join(P.top, old.file);
        const has = fs.existsSync(f);
        const before = has ? fs.readFileSync(f, 'utf8') : null;
        const after = has ? setAdrFileStatus(f, 'superseded', `by ${flags.by}`) : null;
        try {
          appendEvent(P, { type: 'adr.status', id: arg, status: 'superseded', superseded_by: flags.by, by }, has ? snapOf(arg, after) : []);
        } catch (e) {
          if (has && after !== before) fs.writeFileSync(f, before);
          throw e;
        }
        render(P);
        return out(`${arg} superseded by ${flags.by}.${has ? '' : ' (현재 브랜치에 파일이 없어 파일 상태는 병합 때 갱신)'}`);
      }
      if (sub === 'import') {
        // 기존 ADR 폴더를 원장으로 이관. 파일 상태 줄을 그대로 읽고 파일은 바꾸지 않는다. 번호 충돌은 멈추고 보고한다.
        const dir = path.join(P.top, String(arg ?? 'docs/adr'));
        const ref = typeof flags.ref === 'string' ? flags.ref : null; // 다른 브랜치에만 있는 ADR을 체크아웃 없이 이관
        const relDir = path.relative(P.top, dir).split(path.sep).join('/');
        const readAdr = (f) => (ref ? git(['show', `${ref}:${relDir}/${f}`], P.top) ?? '' : fs.readFileSync(path.join(dir, f), 'utf8'));
        const files = (ref ? (git(['ls-tree', '--name-only', `${ref}:${relDir}`], P.top) ?? '').split('\n').filter(Boolean) : fs.readdirSync(dir)).filter((f) => /\.md$/i.test(f)).sort();
        const found = new Map();
        const problems = [];
        const unnumbered = [];
        for (const f of files) {
          if (/template|^index\.md$|^readme\.md$/i.test(f)) continue; // 양식·색인·안내 문서는 결정이 아니다
          const m = /^\d{4}-\d{2}-\d{2}/.test(f) ? null : f.match(/^(?:ADR-?)?(\d{3,4})(?=[-_.])/i);
          if (!m) {
            unnumbered.push(f);
            continue;
          }
          const id = `ADR-${m[1]}`;
          if (found.has(id)) problems.push(`번호 충돌 ${id}: ${found.get(id)} / ${f}`);
          found.set(id, f);
        }
        if (problems.length) throw new Error(`ADR 이관 중단(사용자 결정 필요):\n${problems.join('\n')}`);
        const rel = (f) => path.relative(P.top, path.join(dir, f)).split(path.sep).join('/');
        const later = [];
        const report = [];
        for (const [id, f] of found) {
          if (state.adrs.has(id)) continue;
          const text = readAdr(f);
          const st = adrFileStatus(text);
          if (st === 'superseded') {
            const by2 = (text.match(STATUS_LINE)?.[3] ?? '').match(/ADR-?(\d{3,4})/i);
            later.push({ id, f, text, by: by2 ? `ADR-${by2[1]}` : null });
            continue;
          }
          const status = st ?? 'proposed';
          appendEvent(P, { type: 'adr.status', id, status, file: rel(f), by: 'agent', note: `${st ? 'import' : 'import: 상태 표기 인식 불가'}${ref ? ` (브랜치 ${ref}에만 있음)` : ''}` }, snapOf(id, text));
          report.push(`${id} ${status}${ref ? ` [${ref}]` : ''}${st ? '' : ` (상태 표기 인식 불가: 「${adrStatusRaw(text) || '상태 줄 없음'}」 → 사용자 확인 필요)`}`);
        }
        for (const x of later) {
          const cur = fold(readLedger(P).events).adrs.get(x.by);
          if (x.by && cur?.status === 'accepted') {
            appendEvent(P, { type: 'adr.status', id: x.id, status: 'accepted', file: rel(x.f), by: 'agent', note: 'import' }, snapOf(x.id, x.text));
            appendEvent(P, { type: 'adr.status', id: x.id, status: 'superseded', superseded_by: x.by, by: 'agent', note: 'import' });
            report.push(`${x.id} superseded by ${x.by}`);
          } else {
            appendEvent(P, { type: 'adr.status', id: x.id, status: 'deprecated', file: rel(x.f), by: 'agent', note: 'import: 대체 ADR 불명' }, snapOf(x.id, x.text));
            report.push(`${x.id} 대체됨 표기지만 대체 ADR을 찾지 못함 → 사용자 확인 필요(원장에는 deprecated, 파일 상태와 불일치 오류로 표시됨)`);
          }
        }
        render(P);
        for (const f of unnumbered) report.push(`번호 없는 결정 문서 ${f} → 이관하지 않음. 사용자와 ADR 번호를 정한 뒤 파일명을 바꿔 다시 import한다.`);
        return out(report.join('\n') || '(새로 이관할 ADR 없음)');
      }
      if (sub === 'impact') {
        consumeQuote(P, appendEvent(P, { type: 'adr.impact', id: arg, impact: 'none', reason: flags.reason, by, quote: flags.quote }));
        render(P);
        return out(`${arg} 계획 영향 없음 기록(${by}).`);
      }
      break;
    }
    case 'precommit': {
      // git pre-commit 공통 진입점: 커밋되는 작업트리를 검사한다(미분류 입력·ADR 미반영은 세션 종료 게이트 몫).
      const { errors, warns } = check(P);
      for (const w of warns) process.stderr.write(`WARN ${w}\n`);
      for (const e of errors) process.stderr.write(`ERROR ${e}\n`);
      return errors.length ? 1 : 0;
    }
    case 'triage': {
      const state = fold(readLedger(P).events);
      const rows = listInbox(P).filter((x) => !state.triaged.has(x.id));
      if (flags.list) return out(rows.map((r) => `${r.id} ${r.ts} ${r.tool}${DIRECTIVE_LIKE.test(r.prompt) ? ' [지시형]' : ''} 「${cut(r.prompt, 80)}」`).join('\n') || '(미분류 없음)');
      if (flags['rest-as']) {
        // 나머지 일괄 분류. 지시형 문장은 일괄로 버릴 수 없다(하나씩 판단).
        const risky = rows.filter((r) => DIRECTIVE_LIKE.test(r.prompt));
        if (risky.length) throw new Error(`지시형 입력 ${risky.length}건은 일괄 분류할 수 없다: ${risky.map((r) => r.id).join(', ')}`);
        if (!rows.length) return out('(미분류 없음)');
        appendEvent(P, { type: 'inbox.triage', refs: rows.map((r) => r.id), as: String(flags['rest-as']) });
        return out(`${rows.length}건 → ${flags['rest-as']}.`);
      }
      appendEvent(P, { type: 'inbox.triage', ref: sub, as: flags.as });
      return out(`${sub} → ${flags.as}.`);
    }
    case 'render':
      render(P);
      return out(`${CAPSULE_REL} 갱신.`);
    case 'check': {
      const { errors, warns } = check(P, { close: !!flags.close });
      for (const w of warns) out(`WARN ${w}`);
      for (const e of errors) out(`ERROR ${e}`);
      if (!errors.length) out(`OK plan check${flags.close ? ' --close' : ''}`);
      return errors.length ? 1 : 0;
    }
    case 'stop-gate': {
      // 턴 종료 게이트: 원장 무결성·진입 문서 오류만 막는다. 낡은 캡슐 사본은 조용히 갱신한다. 재차단 루프 방지.
      let o = {};
      try {
        o = JSON.parse(readStdin() || '{}');
      } catch {}
      if (o.stop_hook_active || o.stopHookActive) return 0;
      if (!fs.existsSync(P.ledger)) return 0;
      try {
        render(P);
      } catch {}
      const { errors } = check(P);
      if (errors.length) out(JSON.stringify({ decision: 'block', reason: `[plan] 계획 정본 검사 실패 — 고친 뒤 끝낸다:\n${errors.slice(0, 5).join('\n')}` }));
      return 0;
    }
    case 'capture': {
      // --text 는 설치 세션처럼 훅 밖에서 받은 사용자 원문을 그대로 남길 때 쓴다(요약·의역 금지).
      capture(P, { tool: flags.tool ?? 'unknown', payload: typeof flags.text === 'string' ? JSON.stringify({ prompt: flags.text }) : readStdin() });
      if (flags.remind && (flags.format === 'claude' || flags.format === 'codex')) {
        const r = remind(cwd);
        if (r) out(JSON.stringify({ hookSpecificOutput: { hookEventName: 'UserPromptSubmit', additionalContext: r } }));
      }
      return 0;
    }
    case 'guard': {
      const msg = guard(cwd, readStdin());
      if (msg) {
        process.stderr.write(msg + '\n');
        return 2;
      }
      return 0;
    }
    case 'metrics':
      return out(JSON.stringify(metrics(P), null, 2));
    default:
      out('사용법: plan init|restore|directive add|amend|set|order|revise|adr accept|propose|supersede|import|impact|triage|render|check [--close]|inject|capture|guard|stop-gate|precommit|metrics');
      return cmd ? 1 : 0;
  }
  out(`알 수 없는 하위 명령: ${cmd} ${sub ?? ''}`);
  return 1;
}

if (process.argv[1]?.endsWith('plan.mjs')) {
  try {
    process.exitCode = main(process.argv.slice(2)) ?? 0;
  } catch (e) {
    process.stderr.write(`plan: ${e.message}\n`);
    process.exitCode = 1;
  }
}
